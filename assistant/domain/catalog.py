def get_all_products() -> List[ProductSpec]:
    return list(PRODUCTS)


def get_product_by_id(pid: str) -> Optional[ProductSpec]:
    if not pid:
        return None
    normalized = pid.strip().lower().replace("_", "-")
    for p in PRODUCTS:
        if p.id == normalized or p.backend_id == pid or p.backend_id.replace("_", "-") == normalized:
            return p
    return None
