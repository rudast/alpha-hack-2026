class QASearchEngine:
    """Fast semantic search engine based on stemmed token overlap and TF-IDF weighting."""

    def __init__(self, items: List[QAItem] = KNOWLEDGE_BASE):
        self.items = items
        self.by_id: Dict[str, QAItem] = {item.id: item for item in self.items}
        self.doc_tokens: List[List[str]] = []
        self.idf: Dict[str, float] = {}
        self._build_index()

    def get_by_id(self, item_id: str) -> Optional[QAItem]:
        return self.by_id.get(item_id)

    def _build_index(self):
        n = len(self.items)
        df: Dict[str, int] = {}

        for item in self.items:
            # Index includes question, answer, and keywords
            text = f"{item.question} {item.question} {' '.join(item.keywords)} {item.answer}"
            tokens = tokenize(text)
            self.doc_tokens.append(tokens)
            unique_tokens = set(tokens)
            for t in unique_tokens:
                df[t] = df.get(t, 0) + 1

        for t, freq in df.items():
            self.idf[t] = math.log((n - freq + 0.5) / (freq + 0.5) + 1.0)

    def search(self, query: str, top_k: int = 1, threshold: float = 0.5) -> List[Tuple[QAItem, float]]:
        q_tokens = tokenize(query)
        if not q_tokens:
            return []

        scores: List[Tuple[QAItem, float]] = []

        for idx, item in enumerate(self.items):
            d_tokens = self.doc_tokens[idx]
            d_len = len(d_tokens)
            if d_len == 0:
                continue

            score = 0.0
            # Calculate weighted token overlap
            d_set = set(d_tokens)
            keyword_stems = [simple_ru_stem(k) for k in item.keywords]

            for qt in q_tokens:
                if qt in d_set:
                    weight = self.idf.get(qt, 1.0)
                    # Extra boost if token matches curated keywords
                    if any(qt in kw or kw in qt for kw in keyword_stems):
                        weight *= 2.2
                    score += weight

            # Bonus for exact phrase or question token overlaps
            q_lower = query.lower()
            if any(k in q_lower for k in item.keywords):
                score += 1.5

            if score >= threshold:
                scores.append((item, score))

        scores.sort(key=lambda x: x[1], reverse=True)
        return scores[:top_k]


