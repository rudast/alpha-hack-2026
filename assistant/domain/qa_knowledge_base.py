def simple_ru_stem(word: str) -> str:
    """Lightweight Russian stemmer for keyword search without heavy libraries."""
    w = word.lower().replace("ё", "е")
    if len(w) <= 3:
        return w
    # Strip common inflections
    suffixes = (
        "ами", "ями", "ов", "ев", "ей", "иями", "иям", "иях",
        "ого", "его", "ому", "ему", "ыми", "ых", "их",
        "ую", "юю", "ая", "яя", "ое", "ее", "ые", "ие",
        "ый", "ий", "ой", "ем", "ам", "ям", "ах", "ях",
        "ов", "ев", "ом", "ем", "от", "ет", "ут", "ют",
        "ил", "ал", "ел", "ила", "ала", "ела", "ить", "ать", "еть",
        "ка", "ке", "ку", "ки", "ок", "ек",
        "а", "е", "и", "й", "о", "у", "ы", "ь", "я"
    )
    for s in suffixes:
        if w.endswith(s) and len(w) - len(s) >= 3:
            return w[:-len(s)]
    return w


def tokenize(text: str) -> List[str]:
    """Tokenize and stem text into meaningful search tokens."""
    words = re.findall(r"[а-яa-z0-9]+", text.lower().replace("ё", "е"))
    stopwords = {
        "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как", "а", "то",
        "все", "она", "так", "его", "но", "да", "ты", "к", "у", "же", "вы", "за",
        "бы", "по", "только", "ее", "мне", "было", "вот", "от", "меня", "еще",
        "о", "из", "ему", "теперь", "когда", "даже", "вдруг", "ли", "если", "уже",
        "или", "ни", "быть", "был", "него", "до", "вас", "нибудь", "опять", "уж",
        "вам", "ведь", "там", "потом", "себя", "ничего", "ей", "может", "они",
        "тут", "где", "есть", "надо", "ней", "для", "мы", "тебя", "их", "чем",
        "была", "сам", "чтоб", "без", "будто", "чего", "раз", "тоже", "себе",
        "под", "будет", "ж", "тогда", "кто", "этот", "того", "потому", "этого",
        "какой", "совсем", "ним", "здесь", "этом", "один", "почти", "мой", "тем",
        "чтобы", "нее", "сейчас", "были", "куда", "зачем", "всех", "никогда", "можно",
        "ли", "нужно", "хочу", "подскажи", "скажи", "пожалуйста"
    }
    tokens = [simple_ru_stem(w) for w in words if w not in stopwords and len(w) > 1]
    return tokens


