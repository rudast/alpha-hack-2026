"""Realistic CSV shapes with kopecks and balance checks."""

import base64
import unittest

from worker.services.document_parser import parse_documents


def parse(raw: bytes):
    result = parse_documents({"application_id": "application-1", "documents": [{
        "id": "statement-1", "kind": "account_statement", "filename": "statement.csv",
        "media_type": "text/csv", "content_base64": base64.b64encode(raw).decode("ascii"),
    }]})
    return result["documents"][0]


class AccountStatementCSVTests(unittest.TestCase):
    def test_english_columns_reconcile_kopecks_across_months(self):
        item = parse(b"date,credit,debit,balance\n"
                     b"2025-01-02,100.50,0,1100.50\n"
                     b"2025-01-15,0,40.25,1060.25\n"
                     b"2025-02-03,20,0,1080.25\n")
        self.assertEqual(item["status"], "PARSED")
        fields = item["extracted_fields"]
        self.assertEqual(fields["turnover_monthly"]["value"], [
            {"period": "2025-01", "credit": "100.50", "debit": "40.25"},
            {"period": "2025-02", "credit": "20.00", "debit": "0.00"},
        ])
        self.assertEqual(fields["opening_balance"]["value"], "1000.00")
        self.assertEqual(fields["closing_balance"]["value"], "1080.25")

    def test_russian_cp1251_reverse_order_and_account(self):
        text = ("Дата;Поступление;Списание;Остаток;Номер счёта;Валюта\n"
                "03.02.2025;20,00;;1080,25;40702810000000000001;RUB\n"
                "15.01.2025;;40,25;1060,25;40702810000000000001;RUB\n"
                "02.01.2025;100,50;;1100,50;40702810000000000001;RUB\n")
        item = parse(text.encode("cp1251"))
        self.assertEqual(item["status"], "PARSED")
        self.assertEqual(item["extracted_fields"]["account_number"]["value"],
                         "40702810000000000001")
        self.assertEqual(item["extracted_fields"]["closing_balance"]["value"], "1080.25")

    def test_russian_cp866_headers_are_detected(self):
        item = parse("Дата;Поступление;Списание;Остаток\n"
                     "02.01.2025;100,50;;1100,50\n".encode("cp866"))
        self.assertEqual(item["status"], "PARSED")
        self.assertEqual(item["extracted_fields"]["opening_balance"]["value"], "1000.00")

    def test_short_bank_preamble_is_skipped(self):
        item = parse(b"Account statement\nGenerated by bank\n"
                     b"date,credit,debit,balance\n2025-01-02,100,0,1100\n")
        self.assertEqual(item["status"], "PARSED")

    def test_missing_balance_is_failed(self):
        item = parse(b"date,credit,debit,balance\n2025-01-02,100,0,\n")
        self.assertEqual(item["status"], "FAILED")

    def test_mismatched_balance_is_failed(self):
        item = parse(b"date,credit,debit,balance\n2025-01-02,100,0,1100\n"
                     b"2025-01-03,0,20,999\n")
        self.assertEqual(item["status"], "FAILED")
        self.assertIn("does not reconcile", item["error"])

    def test_foreign_currency_requires_another_adapter(self):
        item = parse(b"date,credit,debit,balance,currency\n2025-01-02,100,0,1100,USD\n")
        self.assertEqual(item["status"], "UNSUPPORTED")

    def test_missing_columns_are_not_guessed(self):
        item = parse(b"date,amount,balance\n2025-01-02,100,1100\n")
        self.assertEqual(item["status"], "UNSUPPORTED")


if __name__ == "__main__":
    unittest.main()
